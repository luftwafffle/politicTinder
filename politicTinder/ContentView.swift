                    .fixedSize(horizontal: false, vertical: true)
                Text("Политика перестаёт быть только предметом философских размышлений.")
                    .font(.title3.weight(.semibold))
                Text("В XIX–XX веках политическая наука постепенно институционализируется как самостоятельная академическая дисциплина. Теперь исследователи не только спрашивают, какой должна быть власть, но и эмпирически изучают, как она реально работает.")
                detailSection("Что исследует политология", "Современная политология исследует государства, политические режимы, партии, выборы, элиты, общественное мнение, политическое поведение, международные отношения и процессы принятия решений.")
                detailSection("Как изучают политику", "Для этого используются сравнительный анализ, статистика, социологические опросы, исторические исследования, математические модели и другие методы.")
                VStack(alignment: .leading, spacing: 20) {
                    detailSection("2500 лет назад", "«Каким должно быть идеальное государство?»")
                    Divider()
                    detailSection("Сегодня", "«Почему конкретные политические системы работают именно так и можем ли мы это проверить на данных?»")
                }
                .padding(22).frame(maxWidth: .infinity, alignment: .leading)
                .background(Palette.wine.opacity(0.08), in: RoundedRectangle(cornerRadius: 22))
                primaryButton("Пройти ещё раз", icon: "arrow.clockwise") { answers = [] }
                Button("На начальный экран") { started = false; answers = [] }
                    .frame(maxWidth: .infinity)
            }.padding(28)
        }
    }

    private func eyebrow(_ text: String) -> some View {
        Text(text).font(.system(size: 11, weight: .bold)).tracking(1.5)
            .foregroundStyle(Palette.wine)
    }

    private func detailSection(_ title: String, _ text: String) -> some View {
        VStack(alignment: .leading, spacing: 10) {
            Text(title).font(.headline)
            Text(text).foregroundStyle(Palette.ink.opacity(0.8))
                .lineSpacing(5).fixedSize(horizontal: false, vertical: true).textSelection(.enabled)
        }
    }

    private func primaryButton(_ title: String, icon: String, action: @escaping () -> Void) -> some View {
        Button(action: action) {
            HStack { Text(title); Spacer(); Image(systemName: icon) }
                .font(.headline).padding(20).foregroundStyle(.white)
                .background(Palette.wine, in: RoundedRectangle(cornerRadius: 18))
        }.buttonStyle(.plain)
    }

    private func choiceButton(_ title: String, icon: String, agrees: Bool) -> some View {
        Button {
            guard answers.count < thinkers.count else { return }
            answers.append(agrees)
        } label: {
            VStack(spacing: 8) {
                Image(systemName: icon).font(.title2.weight(.semibold))
                Text(title).font(.subheadline.weight(.semibold))
            }
            .frame(maxWidth: .infinity).padding(.vertical, 18)
            .foregroundStyle(agrees ? Color.white : Palette.wine)
            .background(agrees ? Palette.wine : Palette.wine.opacity(0.08), in: RoundedRectangle(cornerRadius: 20))
        }.buttonStyle(.plain)
    }
}

private struct Portrait: View {
    let thinker: Thinker

    var body: some View {
        GeometryReader { geometry in
            ZStack {
                thinker.color.opacity(0.3)
                Image(thinker.portraitName)
                    .resizable()
                    .scaledToFit()
                    .frame(width: geometry.size.width, height: geometry.size.height)
                    
            }
            .frame(width: geometry.size.width, height: geometry.size.height)
            .clipShape(RoundedRectangle(cornerRadius: 15))
            .clipped()
        }
        .accessibilityLabel("Портрет: " + thinker.name)
    }
}

